"use client";

import React, { useState } from "react";
import { Cpu } from "lucide-react";
import { useTranslation } from "@/context/LocalizationContext";
import { useClinicalReview } from "@/context/ClinicalReviewContext";

type BenchmarkMode = "Template" | "LLM" | "Hybrid";

export function BenchmarkModeCard() {
  const { t } = useTranslation("uc02");
  const { errorMetrics } = useClinicalReview();
  const [selectedMode, setSelectedMode] = useState<BenchmarkMode>("Template");
  const templateMode = selectedMode === "Template";
  const unsupportedCount = templateMode ? errorMetrics.unsupportedClaims : null;

  return (
    <div className="w-[200px] shrink-0 bg-safe-surface border border-safe-border rounded-[2px] p-2 flex flex-col justify-between select-none">
      {/* Header: Panel title 15–18px */}
      <div className="flex flex-wrap items-center justify-between gap-1 pb-1 border-b border-safe-border shrink-0">
        <div className="flex items-center gap-1.5">
          <Cpu className="w-3.5 h-3.5 text-safe-cyan" />
          <h3 className="text-[13px] font-semibold text-safe-text tracking-tight">
            {t("benchmark.title")}
          </h3>
        </div>
        <span className="text-[9px] font-mono text-safe-text-muted bg-safe-surface-secondary px-1 py-0.2 rounded-[2px] border border-safe-border-light">
          {t("benchmark.secondary")}
        </span>
      </div>

      {/* Compact Mode Selector (Template | LLM | Hybrid) */}
      <div className="grid grid-cols-3 gap-1 my-1 p-0.5 bg-safe-bg border border-safe-border-light rounded-[2px]">
        {(["Template", "LLM", "Hybrid"] as BenchmarkMode[]).map((mode) => (
          <button
            key={mode}
            type="button"
            onClick={() => setSelectedMode(mode)}
            className={`font-mono text-[10px] py-0.5 rounded-[2px] transition-colors ${
              selectedMode === mode
                ? "bg-safe-surface-secondary text-safe-cyan font-bold border border-safe-cyan/60"
                : "text-safe-text-muted hover:text-safe-text"
            }`}
          >
            {t(`benchmark.modes.${mode.toLowerCase()}`)}
          </button>
        ))}
      </div>

      {/* Only the deterministic template output is generated by this replay. */}
      <div className="space-y-1 my-0.5 font-mono text-[11px]">
        <div className="flex justify-between items-center bg-safe-surface-secondary px-2 py-0.5 rounded-[2px] border border-safe-border-light">
          <span className="text-safe-text-muted">{t("benchmark.unsupported")}</span>
          <span
            className={`font-bold tabular-nums ${unsupportedCount === null ? "text-safe-text-muted" : unsupportedCount > 0 ? "text-safe-red" : "text-safe-green"}`}
          >
            {unsupportedCount ?? "—"}
          </span>
        </div>

        <div className="flex justify-between items-center bg-safe-surface-secondary px-2 py-0.5 rounded-[2px] border border-safe-border-light">
          <span className="text-safe-text-muted">{t("benchmark.omissions")}</span>
          <span className="font-bold tabular-nums text-safe-text-muted">
            —
          </span>
        </div>
      </div>

      {/* Description / Secondary notice */}
      <div className="pt-1 border-t border-safe-border-light text-[9px] font-mono text-safe-text-muted truncate shrink-0">
        {t(templateMode ? "benchmark.templateDescription" : "benchmark.unavailableDescription")}
      </div>
    </div>
  );
}
